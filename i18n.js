window.getLang = function () {
    return document.documentElement.lang === 'ar' ? 'ar' : 'en';
};

window.t = function (key) {
    const lang = window.getLang();
    const dict = window.I18N[lang] || window.I18N.en;
    return dict[key] || window.I18N.en[key] || key;
};

window.applyLang = function (lang) {
    const next = lang === 'ar' ? 'ar' : 'en';
    document.documentElement.lang = next;
    document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
    try { localStorage.setItem('lang', next); } catch (_) {}

    const dict = window.I18N[next];

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const value = dict[el.getAttribute('data-i18n')];
        if (value == null) return;
        el.textContent = value;
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const value = dict[el.getAttribute('data-i18n-html')];
        if (value == null) return;
        el.innerHTML = value;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const value = dict[el.getAttribute('data-i18n-placeholder')];
        if (value == null) return;
        el.setAttribute('placeholder', value);
    });

    document.querySelectorAll('.project-blurb, .pcard-blurb, #detailDesc, #detailFeatures, #detailIdeas').forEach((el) => {
        el.dir = next === 'ar' ? 'rtl' : 'ltr';
    });

    document.querySelectorAll('#langToggle [data-lang]').forEach((btn) => {
        btn.classList.toggle('is-active', btn.getAttribute('data-lang') === next);
    });

    if (document.querySelector('.archive-title')) {
        document.title = dict['meta.projects'] || dict['meta.title'];
    } else if (dict['meta.title']) {
        document.title = dict['meta.title'];
    }

    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: next } }));
};
